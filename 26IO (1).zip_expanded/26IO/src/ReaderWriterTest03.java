

/*
예제 주제 설명
----------------------------------
	키보드로 부터 입력받은 내용을  
	1. BufferedReader를 이용해 "한 줄씩" 읽고
	2. 읽은 내용을
	3. BufferedWriter를 이용해 "파일에 한 줄씩" 저장하는 예제
 
 	즉,
 	키보드 입력 -> ReaderWriterTest03.class 프로그램 -> 파일에 저장 
 	흐름을 연습하는 예제이다. 
 */

import java.io.*;
/*
io 패키지
- Input/ Ouput (입력 / 출력) 관련 클래스들이 모여 있는 패키지
- BufferedReader,  BufferedWriter,  FileWriter, InputStreamReader 클래스등이 포함되어 있는 패키지 
*/

public class ReaderWriterTest03 {

	public static void main(String[] args) throws IOException {
		//==============================
		//1. 변수 선언
		//===============================
		
		//사용자가 키보드로 입력한 "파일 이름"을 저장할 변수 
		//예) memo.txt , test.txt
		String fileName = null;
		
		//파일에 저장할 내용을 "한 줄씩" 읽어서 임시로 담아둘 변수
		String buf = null;
		
		//=======================================================================
		//2. 키보드로 부터 입력받은 데이터를 한줄 씩 읽어서 저장할 BufferedReader 입력스트림 생성
		//=======================================================================
		// 이 한 줄에 들어 있는 의미를 단계별로 보면:
		//
		// [1단계] System.in
		// - 키보드와 연결된 입력 통로
		// - 1바이트(byte) 단위로 입력을 받음
		//
		// [2단계] InputStreamReader
		// - 바이트 스트림(System.in)을
		// - 문자 스트림으로 변환
		// - 인코딩 규칙에 따라 바이트 → 문자로 해석
		//
		// [3단계] BufferedReader
		// - 문자 스트림을 "한 줄 단위"로 읽기 위해 사용
		// - 내부에 버퍼(임시 저장 공간)를 사용하여
		//   입력 속도를 빠르게 함
		//
		// 👉 최종 역할:
		// "키보드 입력을 엔터 기준으로 한 줄씩 읽어오는 통로"
		BufferedReader keyBr  = new BufferedReader( new InputStreamReader( System.in ) );
		 
		//==================================
		//3. 파일 이름 입력 받기
		//================================
		System.out.print("파일 이름을 입력하세요->");
		
		//사용자가 키보드로 입력하고 
		//엔터(Enter)를 누를 떄 까지 기다린 후 
		//입력한 내용을 한 줄(String)로 읽어옴
		fileName = keyBr.readLine();
		
		//===================================
		//4. 입력 받은 파일에 저장할 내용 입력 받기
		//==================================
		System.out.println("파일에 기록할 내용을 입력하세요.");
		//이 이후 코드 부터는 사용자가 입력하는 모든 줄의 데이터들을 파일에 저장(기록,출력)할 예정
		
		//==============================================================
		//5. 파일에 저장(출력, 기록)용 출력스트림 통로 -> BufferedWriter객체 생성
		//===============================================================
		//
		// 내부 구조 설명
		//
		// [1 단계] FileWriter클래스의 객체 생성 
		// - 파일과 직접 연결되는 출력스트림 
		// - 문자(char) 단위로 파일에 데이터를 쓰는 통로 
		//
		// [2 단계] BufferedWriter클래스의 객체 생성
		// - FileWriter를 감싸서 한 줄 단위  +  속도 향상 기능을 제공하는 출력 스트림 통로 역할
		//
		// 👉 최종 역할:
		// "문자 데이터를 한 줄씩 파일에 기록하는 출력 스트림 통로"
		BufferedWriter fileBw = new BufferedWriter( new FileWriter(fileName) ); 
		
		// --------------------------------------------------------------
		// [전체 데이터 흐름 모델] 반복 1회가 도는 길 (입력 통로 + 출력 통로 연결)
		//
		//   [키보드]  한 줄 입력 + 엔터
		//     |
		//     v
		//   keyBr (3중 입력 통로 : System.in -> InputStreamReader -> BufferedReader)
		//     |
		//     v  readLine() 이 한 줄을 String 으로 완성
		//   [Stack] buf (참조) --> [Heap] String "입력한 한 줄"
		//     |
		//     v  write(buf) + newLine()
		//   fileBw (2중 출력 통로 : BufferedWriter -> FileWriter)
		//   BufferedWriter 내부 버퍼에 쌓임   <- 이 시점에는 아직 파일에 없다!
		//     |
		//     v  close() 시점에 버퍼가 강제로 비워지며
		//   [디스크 파일]  입력했던 줄들이 순서대로 기록 완료
		//
		// [반복 회차 모델] "안녕" 엔터, "hello" 엔터, 입력 종료 순서로 쳤을 때
		//
		//   회차 | buf 가 가리키는 String | 버퍼에 쌓인 내용 (누적)
		//   -----+-------------------------+--------------------------
		//   1    | "안녕"                  | 안녕(줄바꿈)
		//   2    | "hello"                 | 안녕(줄바꿈)hello(줄바꿈)
		//   3    | null (입력 종료 신호)   | 반복 종료 --> close() 로 파일 확정
		//
		//   입력 종료 방법 : Windows 는 Ctrl+Z 엔터 / Mac,Linux 는 Ctrl+D
		//   문자 스트림의 끝 신호는 -1 이 아니라 null 인 것에 주의 (readLine 기준)
		// --------------------------------------------------------------
		
		//===========================================================
		//6. 키보드로 부터 입력 받은 데이터 읽어서 -> 파일에 저장   이걸 반복처리
		//===========================================================
		/*
		 BufferedReader클래스의 메소드 
		 
			keyBr.readLine()
			- 키보드로 부터 한 줄을 입력 받아 반환 하는 메소드 
			-  입력이  더 이상 없으면 null 을 반환 하는 메소드 
			
			(buf = keyBr.readLine())
			- 키보드로 부터 한 줄 입력 받은 한 줄의 문자열을 반환 받아 buf변수에 저장 
			
			!= null
			- 읽을 데이터가 존재 하는 동안 반복 
		*/
		while( (buf = keyBr.readLine() ) != null  ) {
			
			//======================================
			//7. 파일에 한 줄 기록
			//====================================
			/*
				BufferedWriter 클래스의 메소드 사용
				
				 - write(String 변수) 메소드 
				    매개변수로 전달 받은 한 줄 문자열을 파일에 그대로 기록
				  
				 - newLine() 메소드
				    파일에 엔터(줄바꿈)을 추가 하는 메소드.
				    사용자가 엔터를 누른것과 같은 효과 를 파일에 기록 할수 있다. 
			*/
			fileBw.write(buf);
			fileBw.newLine();
			
			
		}//---while
		
		//======================================
		//8. 사용이 끝난 스트림 통로 닫기 (아주 중요!)
		//======================================
		
		//키보드 입력 스트림(BufferedReader) 종료
		// - 더 이상 키보드 입력한 데이터 읽어들일수 없음 
		keyBr.close();
		
		//파일에 기록하는 출력 스트림(BufferedWriter) 종료
		// - BufferedWriter 객체 메모리 안에 포함되어 있는 내부 버퍼메모리에 남아 있던 데이터를 모두~ 강제로~ 파일에 기록 하고
		// - 파일과의 연결을 해제 하여 더이상 파일에 내보내어 기록할 수 없음
		fileBw.close();

		
	}

}






